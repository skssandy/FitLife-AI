val geminiApiKey: String = run {
    val secretsFile = rootProject.file("secrets.properties")
    if (secretsFile.exists()) {
        secretsFile.readLines()
            .firstOrNull { it.startsWith("GEMINI_API_KEY=") }
            ?.substringAfter("GEMINI_API_KEY=")
            ?.trim()
            ?: ""
    } else {
        ""
    }
}

